// Writes supabase/seed.sql from src/features/exercises/library.ts so the demo
// data and the database seed stay in sync. Run: node scripts/generate-exercise-seed.js
// Pass a migration path to also write the same idempotent insert there, so
// `supabase db push` loads library additions into existing projects.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const { uuidFor } = require('./exercise-seed-id');

const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/features/exercises/library.ts'), 'utf8');
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
});
const mod = { exports: {} };
new Function('module', 'exports', 'require', outputText)(mod, mod.exports, () => ({}));
const { starterExercises } = mod.exports;

const text = (s) => `'${s.replace(/'/g, "''")}'`;
const array = (xs) => `array[${xs.map(text).join(', ')}]::text[]`;

const rows = starterExercises.map(
  (e) =>
    `  (${text(uuidFor(e.id))}, null, ${text(e.name)}, ${array(e.muscleGroups)}, ${text(e.equipment)}, ${text(e.difficulty)}, ${array(e.instructions)}, ${array(e.safetyTips)})`,
);

const sql = `-- Shared CoreFit exercise library (gym_id null = visible to every gym).
-- Generated by scripts/generate-exercise-seed.js from src/features/exercises/library.ts.
insert into public.exercises (id, gym_id, name, muscle_groups, equipment, difficulty, instructions, safety_tips) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;

const targets = ['supabase/seed.sql', ...process.argv.slice(2)];
for (const target of targets) fs.writeFileSync(path.resolve(root, target), sql);
console.log(`Wrote ${rows.length} exercises to ${targets.join(', ')}`);
