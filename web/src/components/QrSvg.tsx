import QRCode from 'qrcode';
import { useEffect, useState } from 'react';

/** A QR code as inline SVG: black on white so any scanner reads it, sharp at any size and in print. */
export function QrSvg({
  value,
  label,
  className,
}: {
  value: string;
  label: string;
  className?: string;
}) {
  const [svg, setSvg] = useState<string | null>(null);
  useEffect(() => {
    let live = true;
    QRCode.toString(value, {
      type: 'svg',
      errorCorrectionLevel: 'M',
      margin: 2,
      color: { dark: '#000000', light: '#ffffff' },
    }).then((s) => live && setSvg(s));
    return () => {
      live = false;
    };
  }, [value]);
  return (
    <div
      className={`qr ${className ?? ''}`}
      role="img"
      aria-label={label}
      // Generated by the qrcode library from our own link; no outside markup.
      dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
    />
  );
}
